"""Regenerate seed.yaml from the supplied workbook (docs/source_specs/Data_Mapping_MCLSPARC.xlsx).

Run: python -m simulated_target_service.build_seed
Orion MCL columns, required flags and tooltips come from the 'Header Tooltips' sheet (ImportRecords); SPARC headers, required flags
and sample values come from 'SPARC - Amplify Mapping'. The workbook describes flat import templates; they are split here into
household, client and account tables so each lines up with one canonical entity. Reference lists hold only values that appear in
the workbooks: the full Orion controlled lists were not supplied."""
import re
from pathlib import Path

import openpyxl
import yaml

ROOT = Path(__file__).resolve().parent
WORKBOOK = ROOT.parent / "docs" / "source_specs" / "Data_Mapping_MCLSPARC.xlsx"
MCL_TABLE = {"HH Grouping Code": "HOUSEHOLD", "Orion Household Id": "HOUSEHOLD", "Household SSN": "HOUSEHOLD", "Household First Name": "HOUSEHOLD",
             "Household Last Name": "HOUSEHOLD", "Household Name": "HOUSEHOLD", "Representative Name": "HOUSEHOLD", "Household DOB": "HOUSEHOLD",
             "Registration Type": "ACCOUNT", "Custodian": "ACCOUNT", "Account Number": "ACCOUNT", "Fund Name": "ACCOUNT", "Open/Closed": "ACCOUNT", "Outside ID": "ACCOUNT"}
SPARC_ACCOUNT = ("Custodian / Fund Family", "Account Number", "Registration Type", "Account Value", "Total Fee", "Contributions", "Current Model",
                 "Model Symbol", "Gain/Loss")
DESCRIPTIONS = {"HOUSEHOLD": "Household grouping and household-level names", "CLIENT": "Account owners (clients), their contact details and identifiers",
                "ACCOUNT": "Custodial accounts"}


def _col(header: str, used: set) -> str:
    text = re.sub(r"\(.*?\)", " ", header.replace("&", " AND ").replace("1st", "FIRST").replace("2nd", "SECOND"))
    words = re.findall(r"[A-Za-z0-9]+", text.upper())
    name = "_".join(words)
    while len(name) > 60 and "_" in name:
        name = name.rsplit("_", 1)[0]
    base, n = name, 2
    while name in used:
        name, n = f"{base}_{n}", n + 1
    used.add(name)
    return name


def _type(header: str) -> str:
    h = header.lower()
    if "dob" in h or "date" in h:
        return "date"
    if h in {"account value", "total fee"}:
        return "number"
    return "string"


def _clean(value) -> str:
    return re.sub(r"\s+", " ", str(value or "")).strip()


def build() -> dict:
    wb = openpyxl.load_workbook(WORKBOOK, read_only=True, data_only=True)
    tables: dict = {}

    def add(table: str, desc: str, header: str, required: bool, description: str, used: dict) -> None:
        t = tables.setdefault(table, {"description": desc, "columns": []})
        t["columns"].append({"name": _col(header, used.setdefault(table, set())), "type": _type(header), "required": required,
                             "description": f"{header}. {description}".strip(" .") + "."})
    used: dict = {}
    for r in wb["Header Tooltips"].iter_rows(min_row=2, values_only=True):
        if r[0] != "ImportRecords" or not r[1]:
            continue
        header, flag, tip = _clean(r[1]), _clean(r[3]), _clean(r[4])
        required = flag == "Required" and not tip.startswith("Conditional")
        part = MCL_TABLE.get(header, "CLIENT")
        add(f"ORION_MCL_{part}", "Orion MasterClientListWizard import: " + DESCRIPTIONS[part], header, required, tip.replace("Required / ", "").replace("Not Required / ", ""), used)
    for r in wb["SPARC - Amplify Mapping"].iter_rows(values_only=True):
        if not (r[1] and str(r[1]).startswith("SPARC - ")) or not r[2] or r[2] == "Target Header":
            continue
        header, flag, sample = _clean(r[2]), _clean(r[3]), _clean(r[4])
        part = "HOUSEHOLD" if header == "Household Name" else ("ACCOUNT" if header.startswith(SPARC_ACCOUNT) else "CLIENT")
        add(f"SPARC_{part}", "SPARC household and account import: " + DESCRIPTIONS[part], header, flag == "" and sample != "" and not header.lower().endswith("address2"),
            f"Example: {sample}." if sample else ("Applies only if applicable." if flag else ""), used)
    return {"system": "Orion MCL and SPARC import targets (simulated)", "version": "0.3.0",
            "code_lists": {"ORION_REF_REGISTRATION_TYPES": ["IRA", "IRA Rollover"], "ORION_REF_CUSTODIANS": ["Pershing", "Schwab", "TD Ameritrade"],
                           "ORION_REF_FUND_NAMES": ["TD Ameritrade"], "ORION_REF_COUNTRIES": []},
            "tables": tables}


HEADER = """# SIMULATED import targets built from the supplied workbook Data_Mapping_MCLSPARC.xlsx (generated by build_seed.py; do not edit by hand).
# Orion MCL (ImportRecords) and SPARC are flat import templates; they are split into household, client and account tables here.
# Reference lists hold only values that appear in the supplied workbooks: the full Orion controlled lists were not supplied.
# The platform never reads this file: it learns the target by inspecting the running service.
"""

if __name__ == "__main__":
    (ROOT / "seed.yaml").write_text(HEADER + yaml.safe_dump(build(), sort_keys=False, allow_unicode=True, width=200), encoding="utf-8")
    print("seed.yaml written")
